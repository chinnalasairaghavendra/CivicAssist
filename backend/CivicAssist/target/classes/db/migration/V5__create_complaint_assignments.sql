CREATE TABLE complaint_assignments (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                       complaint_id BIGINT NOT NULL,

                                       department VARCHAR(100) NOT NULL,

                                       assigned_by BIGINT,

                                       assigned_at TIMESTAMP WITH TIME ZONE
                                           NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                       assignment_note TEXT,

                                       is_current BOOLEAN NOT NULL DEFAULT TRUE,

                                       CONSTRAINT fk_assignment_complaint
                                           FOREIGN KEY (complaint_id)
                                               REFERENCES complaints(id)
                                               ON DELETE CASCADE,

                                       CONSTRAINT fk_assignment_admin
                                           FOREIGN KEY (assigned_by)
                                               REFERENCES users(id)
                                               ON DELETE SET NULL
);

CREATE INDEX idx_assignment_complaint
    ON complaint_assignments(complaint_id);

CREATE INDEX idx_assignment_department
    ON complaint_assignments(department);

CREATE INDEX idx_assignment_assigned_by
    ON complaint_assignments(assigned_by);

CREATE UNIQUE INDEX uq_current_assignment_per_complaint
    ON complaint_assignments(complaint_id)
    WHERE is_current = TRUE;