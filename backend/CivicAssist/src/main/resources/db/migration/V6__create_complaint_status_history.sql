CREATE TABLE complaint_status_history (
                                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                          complaint_id BIGINT NOT NULL,

                                          previous_status VARCHAR(30),

                                          new_status VARCHAR(30) NOT NULL,

                                          changed_by BIGINT,

                                          change_reason VARCHAR(1000),

                                          changed_at TIMESTAMP WITH TIME ZONE
                                              NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                          CONSTRAINT fk_status_history_complaint
                                              FOREIGN KEY (complaint_id)
                                                  REFERENCES complaints(id)
                                                  ON DELETE CASCADE,

                                          CONSTRAINT fk_status_history_user
                                              FOREIGN KEY (changed_by)
                                                  REFERENCES users(id)
                                                  ON DELETE SET NULL
);

CREATE INDEX idx_status_history_complaint_time
    ON complaint_status_history(complaint_id, changed_at DESC);

CREATE INDEX idx_status_history_changed_by
    ON complaint_status_history(changed_by);