CREATE TABLE notifications (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               recipient_id BIGINT NOT NULL,
                               complaint_id BIGINT,

                               title VARCHAR(150) NOT NULL,
                               message VARCHAR(1000) NOT NULL,
                               type VARCHAR(50) NOT NULL,

                               is_read BOOLEAN NOT NULL DEFAULT FALSE,

                               created_at TIMESTAMP WITH TIME ZONE
                                   NOT NULL DEFAULT CURRENT_TIMESTAMP,

                               read_at TIMESTAMP WITH TIME ZONE,

                               CONSTRAINT fk_notification_recipient
                                   FOREIGN KEY (recipient_id)
                                       REFERENCES users(id),

                               CONSTRAINT fk_notification_complaint
                                   FOREIGN KEY (complaint_id)
                                       REFERENCES complaints(id),

                               CONSTRAINT chk_notification_type
                                   CHECK (
                                       type IN (
                                                'COMPLAINT_SUBMITTED',
                                                'COMPLAINT_ASSIGNED',
                                                'STATUS_CHANGED',
                                                'RESOLUTION_SUBMITTED',
                                                'REOPENING_REQUEST_REVIEWED'
                                           )
                                       ),

                               CONSTRAINT chk_notification_read_at
                                   CHECK (
                                       (is_read = FALSE AND read_at IS NULL)
                                           OR
                                       (is_read = TRUE AND read_at IS NOT NULL)
                                       )
);

-- Retrieve a user's notifications in chronological order.
CREATE INDEX idx_notifications_recipient_created
    ON notifications(recipient_id, created_at DESC);

-- Retrieve unread notifications efficiently.
CREATE INDEX idx_notifications_recipient_unread
    ON notifications(recipient_id, created_at DESC)
    WHERE is_read = FALSE;

-- Find notifications associated with a complaint.
CREATE INDEX idx_notifications_complaint
    ON notifications(complaint_id);

-- Support efficient retention cleanup.
CREATE INDEX idx_notifications_cleanup
    ON notifications(is_read, read_at, created_at);