CREATE TABLE complaint_resolutions (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                       complaint_id BIGINT NOT NULL,

                                       resolution_notes TEXT NOT NULL,

                                       evidence_url VARCHAR(2048),

                                       resolved_by BIGINT,

                                       resolved_at TIMESTAMP WITH TIME ZONE NOT NULL
                                           DEFAULT CURRENT_TIMESTAMP,

                                       CONSTRAINT fk_resolution_complaint
                                           FOREIGN KEY (complaint_id)
                                               REFERENCES complaints(id)
                                               ON DELETE CASCADE,

                                       CONSTRAINT fk_resolution_user
                                           FOREIGN KEY (resolved_by)
                                               REFERENCES users(id)
                                               ON DELETE SET NULL
);

CREATE INDEX idx_resolution_complaint
    ON complaint_resolutions(complaint_id);

CREATE INDEX idx_resolution_resolved_by
    ON complaint_resolutions(resolved_by);

CREATE INDEX idx_resolution_complaint_time
    ON complaint_resolutions(complaint_id, resolved_at DESC);