CREATE TABLE complaint_attachments (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                       complaint_id BIGINT NOT NULL,

                                       original_filename VARCHAR(255) NOT NULL,
                                       stored_filename VARCHAR(100) NOT NULL UNIQUE,
                                       content_type VARCHAR(100) NOT NULL,
                                       file_size BIGINT NOT NULL,

                                       uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                       CONSTRAINT fk_complaint_attachments_complaint
                                           FOREIGN KEY (complaint_id)
                                               REFERENCES complaints(id)
                                               ON DELETE CASCADE,

                                       CONSTRAINT chk_complaint_attachment_file_size
                                           CHECK (file_size > 0 AND file_size <= 5242880)
);

CREATE INDEX idx_complaint_attachments_complaint_id
    ON complaint_attachments(complaint_id);