CREATE TABLE complaint_comments (
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                    complaint_id BIGINT NOT NULL,

                                    author_id BIGINT,

                                    content TEXT NOT NULL,

                                    created_at TIMESTAMP WITH TIME ZONE NOT NULL
                                        DEFAULT CURRENT_TIMESTAMP,

                                    CONSTRAINT fk_comment_complaint
                                        FOREIGN KEY (complaint_id)
                                            REFERENCES complaints(id)
                                            ON DELETE CASCADE,

                                    CONSTRAINT fk_comment_author
                                        FOREIGN KEY (author_id)
                                            REFERENCES users(id)
                                            ON DELETE SET NULL,

                                    CONSTRAINT chk_comment_content
                                        CHECK (LENGTH(TRIM(content)) > 0)
);

CREATE INDEX idx_comment_complaint_time
    ON complaint_comments(complaint_id, created_at ASC);

CREATE INDEX idx_comment_author
    ON complaint_comments(author_id);