CREATE TABLE complaint_reopening_requests (
                                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                              complaint_id BIGINT NOT NULL,
                                              requested_by BIGINT NOT NULL,

                                              reason VARCHAR(1000) NOT NULL,

                                              status VARCHAR(20) NOT NULL DEFAULT 'PENDING',

                                              reviewed_by BIGINT,
                                              admin_comment VARCHAR(1000),

                                              created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                              reviewed_at TIMESTAMP WITH TIME ZONE,

                                              CONSTRAINT fk_reopening_request_complaint
                                                  FOREIGN KEY (complaint_id)
                                                      REFERENCES complaints(id),

                                              CONSTRAINT fk_reopening_request_user
                                                  FOREIGN KEY (requested_by)
                                                      REFERENCES users(id),

                                              CONSTRAINT fk_reopening_request_reviewer
                                                  FOREIGN KEY (reviewed_by)
                                                      REFERENCES users(id),

                                              CONSTRAINT chk_reopening_request_status
                                                  CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE INDEX idx_reopening_requests_complaint
    ON complaint_reopening_requests(complaint_id);

CREATE INDEX idx_reopening_requests_status_created
    ON complaint_reopening_requests(status, created_at DESC);

CREATE UNIQUE INDEX uq_pending_reopening_request_per_complaint
    ON complaint_reopening_requests(complaint_id)
    WHERE status = 'PENDING';